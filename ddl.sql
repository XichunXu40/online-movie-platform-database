DROP TABLE IF EXISTS user_genre_preferences CASCADE;
DROP TABLE IF EXISTS viewing_history CASCADE;
DROP TABLE IF EXISTS watchlist_items CASCADE;
DROP TABLE IF EXISTS review_comments CASCADE;
DROP TABLE IF EXISTS reviews CASCADE;
DROP TABLE IF EXISTS movie_genres CASCADE;
DROP TABLE IF EXISTS genres CASCADE;
DROP TABLE IF EXISTS movies CASCADE;
DROP TABLE IF EXISTS user_profiles CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL UNIQUE
        CHECK (LENGTH(TRIM(username)) >= 3),
    email VARCHAR(100) NOT NULL UNIQUE
        CHECK (email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'),
    password_hash VARCHAR(255) NOT NULL,
    registration_date DATE NOT NULL DEFAULT CURRENT_DATE,
    account_status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (account_status IN ('active', 'suspended', 'deleted')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_profiles (
    profile_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE,
    display_name VARCHAR(50) NOT NULL CHECK (LENGTH(TRIM(display_name)) >= 2),
    country VARCHAR(60),
    date_of_birth DATE,
    preferred_language VARCHAR(40) NOT NULL DEFAULT 'English',
    marketing_opt_in BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_profile_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE CASCADE
);

CREATE TABLE movies (
    movie_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    release_year INTEGER NOT NULL CHECK (release_year BETWEEN 1900 AND 2026),
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
    original_language VARCHAR(40) NOT NULL,
    country VARCHAR(60),
    maturity_rating VARCHAR(10) NOT NULL
        CHECK (maturity_rating IN ('G', 'PG', 'PG-13', 'R', 'NC-17', 'U', '12A', '15', '18')),
    synopsis TEXT,
    added_date DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_movie_title_year UNIQUE (title, release_year)
);

CREATE TABLE genres (
    genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name VARCHAR(40) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE movie_genres (
    movie_id INTEGER NOT NULL,
    genre_id INTEGER NOT NULL,
    PRIMARY KEY (movie_id, genre_id),
    CONSTRAINT fk_movie_genres_movie
        FOREIGN KEY (movie_id) REFERENCES movies(movie_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_movie_genres_genre
        FOREIGN KEY (genre_id) REFERENCES genres(genre_id)
        ON DELETE CASCADE
);

CREATE TABLE reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    movie_id INTEGER NOT NULL,
    rating NUMERIC(2,1) NOT NULL CHECK (rating BETWEEN 1.0 AND 5.0),
    review_title VARCHAR(100),
    review_text TEXT,
    review_date DATE NOT NULL DEFAULT CURRENT_DATE,
    review_status VARCHAR(20) NOT NULL DEFAULT 'visible'
        CHECK (review_status IN ('visible', 'hidden', 'flagged')),
    UNIQUE (user_id, movie_id),
    CONSTRAINT fk_reviews_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_reviews_movie
        FOREIGN KEY (movie_id) REFERENCES movies(movie_id)
        ON DELETE CASCADE
);

CREATE TABLE review_comments (
    comment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    comment_text TEXT NOT NULL,
    comment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    comment_status VARCHAR(20) NOT NULL DEFAULT 'visible'
        CHECK (comment_status IN ('visible', 'hidden', 'flagged')),
    CONSTRAINT fk_comments_review
        FOREIGN KEY (review_id) REFERENCES reviews(review_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_comments_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE CASCADE
);

CREATE TABLE watchlist_items (
    watchlist_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    movie_id INTEGER NOT NULL,
    added_date DATE NOT NULL DEFAULT CURRENT_DATE,
    priority_level INTEGER NOT NULL DEFAULT 3 CHECK (priority_level BETWEEN 1 AND 5),
    watched BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (user_id, movie_id),
    CONSTRAINT fk_watchlist_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_watchlist_movie
        FOREIGN KEY (movie_id) REFERENCES movies(movie_id)
        ON DELETE CASCADE
);

CREATE TABLE viewing_history (
    viewing_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    movie_id INTEGER NOT NULL,
    watched_at TIMESTAMP NOT NULL,
    progress_minutes INTEGER NOT NULL CHECK (progress_minutes >= 0),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    device_type VARCHAR(30) NOT NULL
        CHECK (device_type IN ('mobile', 'desktop', 'tablet', 'smart_tv')),
    CONSTRAINT fk_history_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_history_movie
        FOREIGN KEY (movie_id) REFERENCES movies(movie_id)
        ON DELETE CASCADE
);

CREATE TABLE user_genre_preferences (
    user_id INTEGER NOT NULL,
    genre_id INTEGER NOT NULL,
    preference_score INTEGER NOT NULL CHECK (preference_score BETWEEN 1 AND 5),
    created_at DATE NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (user_id, genre_id),
    CONSTRAINT fk_preferences_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_preferences_genre
        FOREIGN KEY (genre_id) REFERENCES genres(genre_id)
        ON DELETE CASCADE
);

-- Indexes support common DQL operations without changing the logical model.
CREATE INDEX idx_reviews_movie_id ON reviews(movie_id);
CREATE INDEX idx_movie_genres_genre_id ON movie_genres(genre_id);
CREATE INDEX idx_viewing_history_user_id ON viewing_history(user_id);
CREATE INDEX idx_watchlist_user_priority ON watchlist_items(user_id, priority_level);
